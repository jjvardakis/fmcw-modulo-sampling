function checks = verify_recovery
%VERIFY_RECOVERY Validate algebra and exact recovery on the supplied reference scene.
root=fileparts(mfilename('fullpath')); addpath(root);
setup_scene; rng(1);
a=amp.*exp(1i*2*pi*rand(1,2));
r=fmcw_beat(R,a,fc,B,Tc,N);
zI=modlam(real(r),lam); zQ=modlam(imag(r),lam);
eI=real(r)-zI; eQ=imag(r)-zQ;
D=@(x)circshift(x,-1)-x;
[hI,hQ,info]=hpof(zI,zQ,lam);
truth=find(abs(D(eI))>1e-8|abs(D(eQ))>1e-8)-1;
checks=table(norm(dht(imag(r))-real(r),inf), ...
 norm(info.d-(dht(eQ)-eI),inf), ...
 norm(info.g-(dht(D(eQ))-D(eI)),inf), ...
 norm(hI+1i*hQ-r,inf),numel(truth),info.K, ...
 isequal(info.folds(:),truth(:)), ...
 max(abs([diff(real(r));diff(imag(r))]))/lam, ...
 norm(itoh(zI)+1i*itoh(zQ)-r,inf), ...
 'VariableNames',{'hilbertError','cancellationError','differenceError', ...
 'recoveryError','trueFoldCount','selectedOrder','exactSupport', ...
 'maxDifferenceOverLambda','itohError'});
folder=fullfile(root,'results'); if ~exist(folder,'dir'),mkdir(folder);end
writetable(checks,fullfile(folder,'baseline_checks.csv')); disp(checks);
assert(checks.hilbertError<1e-9 && checks.cancellationError<1e-9 ...
 && checks.differenceError<1e-9,'Algebra failed.');
assert(checks.recoveryError<1e-6 && checks.exactSupport,'Baseline recovery failed.');
% Verify the calibrated cancellation and reconstruction independently.
gain=.1; phase=3*pi/180; q=(1+gain)*(imag(r)*cos(phase)+real(r)*sin(phase));
[hi,hq]=hpof(zI,modlam(q,lam),lam,gain,phase);
assert(norm(hi+1i*hq-(real(r)+1i*q),inf)<1e-6, ...
 'Calibrated imbalance recovery failed.');
fprintf('Baseline and calibrated-imbalance checks passed.\n');
end
